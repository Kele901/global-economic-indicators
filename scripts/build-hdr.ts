// Regenerates src/app/services/developmentCurated/hdrData.ts from the UNDP
// Human Development Report composite-indices time series CSV.
//
//   npx tsx scripts/build-hdr.ts path/to/HDR25_Composite_indices_complete_time_series.csv
//
// Download: https://hdr.undp.org/data-center/documentation-and-downloads

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COUNTRY_ISO3, ISO3_TO_COUNTRY } from '../src/app/utils/countryMappings';

const DATA_YEAR = 2023;
const TREND_FROM = 1990;

function parseCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

function main() {
  const path = process.argv[2];
  if (!path) {
    console.error('usage: tsx scripts/build-hdr.ts <csv>');
    process.exit(1);
  }
  const lines = readFileSync(path, 'latin1').split(/\r?\n/).filter(Boolean);
  const header = parseCsvLine(lines[0]);
  const col = (name: string) => header.indexOf(name);

  const num = (row: string[], name: string, digits = 3): number | null => {
    const i = col(name);
    if (i < 0) return null;
    const v = parseFloat(row[i]);
    return Number.isFinite(v) ? Number(v.toFixed(digits)) : null;
  };

  const rows: Record<string, unknown> = {};
  for (const line of lines.slice(1)) {
    const row = parseCsvLine(line);
    const key = ISO3_TO_COUNTRY[row[0]];
    if (!key) continue;
    const y = DATA_YEAR;
    const trend: Record<number, number> = {};
    for (let yr = TREND_FROM; yr <= y; yr++) {
      const v = num(row, `hdi_${yr}`);
      if (v != null) trend[yr] = v;
    }
    rows[key] = {
      hdiRank: num(row, `hdi_rank_${y}`, 0),
      hdi: num(row, `hdi_${y}`),
      lifeExpectancy: num(row, `le_${y}`, 1),
      expectedSchooling: num(row, `eys_${y}`, 1),
      meanSchooling: num(row, `mys_${y}`, 1),
      gniPerCapita: num(row, `gnipc_${y}`, 0),
      ihdi: num(row, `ihdi_${y}`),
      ihdiLoss: num(row, `loss_${y}`, 1),
      inequalityLife: num(row, `ineq_le_${y}`, 1),
      inequalityEducation: num(row, `ineq_edu_${y}`, 1),
      inequalityIncome: num(row, `ineq_inc_${y}`, 1),
      gdi: num(row, `gdi_${y}`),
      gdiGroup: num(row, `gdi_group_${y}`, 0),
      hdiFemale: num(row, `hdi_f_${y}`),
      hdiMale: num(row, `hdi_m_${y}`),
      gii: num(row, `gii_${y}`),
      giiRank: num(row, `gii_rank_${y}`, 0),
      maternalMortality: num(row, `mmr_${y}`, 0),
      adolescentBirths: num(row, `abr_${y}`, 1),
      parliamentFemale: num(row, `pr_f_${y}`, 1),
      secondaryEdFemale: num(row, `se_f_${y}`, 1),
      secondaryEdMale: num(row, `se_m_${y}`, 1),
      labourForceFemale: num(row, `lfpr_f_${y}`, 1),
      labourForceMale: num(row, `lfpr_m_${y}`, 1),
      phdi: num(row, `phdi_${y}`),
      co2PerCapita: num(row, `co2_prod_${y}`, 2),
      materialFootprint: num(row, `mf_${y}`, 2),
      populationMillions: num(row, `pop_total_${y}`, 2),
      trend,
    };
  }

  const missing = Object.keys(COUNTRY_ISO3).filter((k) => !rows[k]);
  if (missing.length) console.warn('Missing from CSV:', missing.join(', '));

  const body = `// GENERATED by scripts/build-hdr.ts from the UNDP HDR 2025 composite-indices
// time series (data year ${DATA_YEAR}). Do not edit by hand; rerun the script.

import type { HdrRecord } from './types';
import type { CountryKey } from '../../utils/countryMappings';

export const HDR_DATA_YEAR = ${DATA_YEAR};

export const HDR: Partial<Record<CountryKey, HdrRecord>> = ${JSON.stringify(rows, null, 2)};
`;
  const out = resolve(__dirname, '../src/app/services/developmentCurated/hdrData.ts');
  writeFileSync(out, body, 'utf8');
  console.log(`Wrote ${Object.keys(rows).length} countries to ${out}`);
}

main();
