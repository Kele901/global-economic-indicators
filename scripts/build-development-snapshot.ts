// Regenerates src/app/services/developmentCurated/snapshotData.ts:
//  - World income distribution (share of people below each $/day line, 2021 PPP)
//    from the World Bank Poverty and Inequality Platform.
//  - Population projections for 2030 and 2050 from World Bank source 40
//    (Population estimates and projections, based on UN WPP).
//
//   npx tsx scripts/build-development-snapshot.ts

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COUNTRY_ISO3, ISO3_TO_COUNTRY } from '../src/app/utils/countryMappings';

const PIP_YEAR = 2022;
const LINES = [
  1, 1.5, 2, 2.5, 3, 3.5, 4.2, 5, 6, 7, 8.3, 10, 12, 14, 17, 20, 24, 28, 34, 40, 50, 60, 75, 90, 110, 140, 180,
];

async function getJson(url: string): Promise<any> {
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url);
    if (res.ok) return res.json();
    await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
  }
  throw new Error(`Failed: ${url}`);
}

async function globalDistribution() {
  const points: { dailyIncome: number; shareBelow: number }[] = [];
  let mean = 0;
  for (const line of LINES) {
    const url = `https://api.worldbank.org/pip/v1/pip-grp?country=WLD&year=${PIP_YEAR}&povline=${line}&group_by=wb&format=json`;
    const json = await getJson(url);
    const row = Array.isArray(json) ? json[0] : null;
    if (!row) continue;
    mean = row.mean;
    points.push({ dailyIncome: line, shareBelow: Number((row.headcount * 100).toFixed(2)) });
  }
  return { mean: Number(mean.toFixed(2)), points };
}

async function projections() {
  const iso = Object.values(COUNTRY_ISO3).join(';');
  const url = `https://api.worldbank.org/v2/country/${iso}/indicator/SP.POP.TOTL?source=40&date=2023:2050&format=json&per_page=5000`;
  const json = await getJson(url);
  const rows: any[] = json[1] || [];
  const out: Record<string, Record<string, number>> = {};
  for (const r of rows) {
    const key = ISO3_TO_COUNTRY[r.countryiso3code];
    const year = Number(r.date);
    if (!key || r.value == null || ![2023, 2030, 2040, 2050].includes(year)) continue;
    (out[key] ||= {})[year] = Number((r.value / 1e6).toFixed(2));
  }
  return out;
}

const INCOME_LEVELS: Record<string, string> = {
  HIC: 'High income',
  UMC: 'Upper-middle income',
  LMC: 'Lower-middle income',
  LIC: 'Low income',
};

async function incomeGroups() {
  const json = await getJson('https://api.worldbank.org/v2/country?format=json&per_page=400');
  const out: Record<string, string> = {};
  for (const c of json[1] || []) {
    const key = ISO3_TO_COUNTRY[c.id];
    const level = INCOME_LEVELS[c.incomeLevel?.id];
    if (key && level) out[key] = level;
  }
  return out;
}

async function humanCapital() {
  const iso = Object.values(COUNTRY_ISO3).join(';');
  const url = `https://api.worldbank.org/v2/country/${iso}/indicator/HD.HCI.OVRL?source=63&format=json&per_page=5000`;
  const json = await getJson(url);
  const out: Record<string, { year: number; value: number }> = {};
  for (const r of json[1] || []) {
    const key = ISO3_TO_COUNTRY[r.countryiso3code];
    if (!key || r.value == null) continue;
    const year = Number(r.date);
    if (!out[key] || year > out[key].year) out[key] = { year, value: Number(r.value.toFixed(3)) };
  }
  return out;
}

async function main() {
  const dist = await globalDistribution();
  const proj = await projections();
  const groups = await incomeGroups();
  const hci = await humanCapital();
  const body = `// GENERATED by scripts/build-development-snapshot.ts. Do not edit by hand.

export const GLOBAL_INCOME_YEAR = ${PIP_YEAR};
// World mean income, $/person/day at 2021 PPP.
export const GLOBAL_INCOME_MEAN = ${dist.mean};
// Share of the world's population living below each daily income line.
export const GLOBAL_INCOME_CDF: { dailyIncome: number; shareBelow: number }[] = ${JSON.stringify(dist.points, null, 2)};

// Population in millions (UN WPP medium variant via World Bank source 40).
export const POPULATION_PROJECTIONS: Record<string, Record<string, number>> = ${JSON.stringify(proj, null, 2)};

// World Bank income classification (current fiscal year) from the country API.
export const INCOME_GROUP_SNAPSHOT: Record<string, string> = ${JSON.stringify(groups, null, 2)};

// Latest World Bank Human Capital Index (source 63).
export const HCI_SNAPSHOT: Record<string, { year: number; value: number }> = ${JSON.stringify(hci, null, 2)};
`;
  const outPath = resolve(__dirname, '../src/app/services/developmentCurated/snapshotData.ts');
  writeFileSync(outPath, body, 'utf8');
  console.log(
    `Wrote ${dist.points.length} income points, ${Object.keys(proj).length} projections, ` +
      `${Object.keys(groups).length} income groups, ${Object.keys(hci).length} HCI`
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
